// 会员资料「国籍」存储格式："中国 广东省 深圳市 南山区"（空段过滤后空格连接）
export function composeNationality(parts: (string | null | undefined)[]): string {
  return parts.map((p) => (p || "").trim()).filter(Boolean).join(" ");
}
