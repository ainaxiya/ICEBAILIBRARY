// 构建独立消费进程产物：worker/main.ts → worker/main.cjs
// 说明：
//   · 应用源码（含 @/ 路径别名）打进产物，保证服务器不需要 TS 运行时；
//   · npm 依赖（bullmq / ioredis / @prisma/client / dotenv 等）保持 external，
//     直接复用服务器已有的 node_modules，不额外上传依赖；
//   · esbuild 只在本地构建时使用（devDependency），服务器不参与构建。
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.join(root, "src");

function resolveTs(base) {
  const candidates = [base, `${base}.ts`, `${base}.tsx`, path.join(base, "index.ts")];
  for (const p of candidates) {
    if (fs.existsSync(p) && fs.statSync(p).isFile()) return p;
  }
  return base;
}

// server-only 是 Next.js 内置的空标记包，不在 node_modules 里；消费进程属服务端，
// 直接内联成空模块，避免产物在服务器上 require 失败。
const serverOnlyPlugin = {
  name: "server-only-stub",
  setup(b) {
    b.onResolve({ filter: /^server-only$/ }, () => ({ path: "server-only", namespace: "server-only-stub" }));
    b.onLoad({ filter: /.*/, namespace: "server-only-stub" }, () => ({
      contents: "module.exports = {};",
      loader: "js",
    }));
  },
};

// 把 "@/lib/xxx" 解析到 src/lib/xxx（与 tsconfig paths 一致）
const aliasPlugin = {
  name: "tsconfig-paths",
  setup(b) {
    b.onResolve({ filter: /^@\// }, (args) => ({
      path: resolveTs(path.join(srcDir, args.path.slice(2))),
    }));
  },
};

await build({
  entryPoints: [path.join(root, "worker", "main.ts")],
  outfile: path.join(root, "worker", "main.cjs"),
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node20",
  packages: "external",
  plugins: [serverOnlyPlugin, aliasPlugin],
  logLevel: "info",
  banner: { js: "// generated by scripts/build-worker.mjs - do not edit" },
});
